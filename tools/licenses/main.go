// Command licenses writes THIRD_PARTY_LICENSES.txt: the license text of
// every Go module compiled into netdiag for the release targets, plus the
// bundled web assets. Run it from the repository root after changing
// dependencies or vendored assets:
//
//	go run ./tools/licenses            # rewrite THIRD_PARTY_LICENSES.txt
//	go run ./tools/licenses -check     # exit 1 if the file is out of date
//
// It is a development tool; netdiag itself never runs it.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// targets are the release platforms (scripts/build.*).
var targets = []string{"windows/amd64", "windows/arm64", "darwin/amd64", "darwin/arm64"}

// assets are the third-party files embedded through web/.
var assets = []struct{ name, license string }{
	{"Alpine.js 3.14.9 (web/vendor/alpine.min.js)", "web/vendor/LICENSE-alpine.txt"},
	{"Inter Variable font (web/vendor/fonts/Inter-Variable-latin.woff2)", "web/vendor/fonts/OFL-Inter.txt"},
	{"JetBrains Mono fonts (web/vendor/fonts/JetBrainsMono-latin-*.woff2)", "web/vendor/fonts/OFL-JetBrainsMono.txt"},
	{"Lucide icons (web/icons.svg)", "web/vendor/LICENSE-lucide.txt"},
}

const out = "THIRD_PARTY_LICENSES.txt"

type module struct {
	Path, Version, Dir string
	Main               bool
}

func main() {
	check := flag.Bool("check", false, "exit 1 if "+out+" is out of date instead of writing it")
	flag.Parse()
	text, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(1)
	}
	if *check {
		old, _ := os.ReadFile(out)
		if !bytes.Equal(normalize(old), normalize(text)) {
			fmt.Fprintln(os.Stderr, out+" is out of date: run go run ./tools/licenses")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(out, text, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(1)
	}
}

// normalize ignores line-ending differences from git checkouts.
func normalize(b []byte) []byte { return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")) }

func generate() ([]byte, error) {
	mods := map[string]module{}
	for _, t := range targets {
		goos, goarch, _ := strings.Cut(t, "/")
		list, err := deps(goos, goarch)
		if err != nil {
			return nil, err
		}
		for _, m := range list {
			mods[m.Path+"@"+m.Version] = m
		}
	}
	keys := make([]string, 0, len(mods))
	for k := range mods {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	b.WriteString("Third-party licenses for netdiag\n")
	b.WriteString("================================\n\n")
	b.WriteString("netdiag is licensed under the Apache License, Version 2.0 (see LICENSE).\n")
	b.WriteString("The netdiag binary includes the following third-party components.\n")
	b.WriteString("This file is generated by tools/licenses; do not edit it by hand.\n\n")
	b.WriteString("Bundled web assets\n------------------\n")
	for _, a := range assets {
		b.WriteString("  " + a.name + "\n")
	}
	b.WriteString("\nGo modules\n----------\n")
	for _, k := range keys {
		b.WriteString("  " + k + "\n")
	}
	b.WriteString("\nIEEE MA-L (OUI) registry data (internal/oui/oui.csv.gz) is public\n")
	b.WriteString("registration data from the IEEE Registration Authority.\n")

	for _, a := range assets {
		text, err := os.ReadFile(a.license)
		if err != nil {
			return nil, err
		}
		section(&b, a.name, text)
	}
	for _, k := range keys {
		text, err := moduleLicenses(mods[k].Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", k, err)
		}
		section(&b, k, text)
	}
	return b.Bytes(), nil
}

func section(b *bytes.Buffer, name string, text []byte) {
	b.WriteString("\n\n" + strings.Repeat("=", 78) + "\n" + name + "\n" + strings.Repeat("=", 78) + "\n\n")
	b.Write(bytes.TrimSpace(normalize(text)))
	b.WriteString("\n")
}

// deps lists the non-main modules linked into ./cmd/netdiag for one target.
func deps(goos, goarch string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-json=Module", "./cmd/netdiag")
	cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0")
	cmd.Stderr = os.Stderr
	outb, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list for %s/%s: %w", goos, goarch, err)
	}
	var list []module
	dec := json.NewDecoder(bytes.NewReader(outb))
	for {
		var p struct{ Module *module }
		if err := dec.Decode(&p); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		if p.Module != nil && !p.Module.Main {
			list = append(list, *p.Module)
		}
	}
	return list, nil
}

// moduleLicenses returns the LICENSE, COPYING and NOTICE files at the root
// of a module, in name order.
func moduleLicenses(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	for _, e := range entries {
		n := strings.ToUpper(e.Name())
		if e.IsDir() || !(strings.HasPrefix(n, "LICENSE") || strings.HasPrefix(n, "LICENCE") ||
			strings.HasPrefix(n, "COPYING") || strings.HasPrefix(n, "NOTICE")) {
			continue
		}
		text, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if b.Len() > 0 {
			b.WriteString("\n\n--- " + e.Name() + " ---\n\n")
		}
		b.Write(text)
	}
	if b.Len() == 0 {
		return nil, fmt.Errorf("no license file in %s", dir)
	}
	return b.Bytes(), nil
}
