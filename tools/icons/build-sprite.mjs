// Dev-only: builds ../../web/icons.svg from lucide-static (pinned in package.json).
// Usage: npm ci && node build-sprite.mjs
import { readFileSync, writeFileSync, existsSync, copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const LUCIDE = join(here, 'node_modules', 'lucide-static');
const ICON_DIR = join(LUCIDE, 'icons');
const OUT = join(here, '..', '..', 'web', 'icons.svg');
const VENDOR = join(here, '..', '..', 'web', 'vendor');
const MAX_BYTES = 40960;

const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const pinned = pkg.dependencies['lucide-static'];
const lucideVersion = JSON.parse(readFileSync(join(LUCIDE, 'package.json'), 'utf8')).version;
if (lucideVersion !== pinned) {
  throw new Error(`installed lucide-static ${lucideVersion} != pinned ${pinned}; run npm ci`);
}

const entries = [];
const seen = new Set();
for (const [i, raw] of readFileSync(join(here, 'icons.txt'), 'utf8').split(/\r?\n/).entries()) {
  const line = raw.replace(/#.*$/, '').trim();
  if (!line) continue;
  const parts = line.split(/\s+/);
  if (parts.length !== 2) throw new Error(`icons.txt:${i + 1}: expected "<sprite-id> <lucide-name>"`);
  const [id, name] = parts;
  if (seen.has(id)) throw new Error(`icons.txt:${i + 1}: duplicate sprite id ${id}`);
  seen.add(id);
  entries.push({ id, name });
}
entries.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const symbols = entries.map(({ id, name }) => {
  const file = join(ICON_DIR, `${name}.svg`);
  if (!existsSync(file)) throw new Error(`missing lucide icon "${name}" (sprite ${id}); check icons.txt / renamed icons in lucide-static ${pinned}`);
  const src = readFileSync(file, 'utf8');
  const vb = src.match(/viewBox="([^"]+)"/);
  const open = src.match(/<svg\b[^>]*>/);
  if (!vb || !open) throw new Error(`unparseable svg: ${name}`);
  let inner = src.slice(src.indexOf(open[0]) + open[0].length, src.lastIndexOf('</svg>'));
  inner = inner
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+class="[^"]*"/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
  return `  <symbol id="${id}" viewBox="${vb[1]}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
});

const out = [
  `<!-- Lucide v${pinned} (ISC) — generated by tools/icons/build-sprite.mjs; do not edit -->`,
  '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
  ...symbols,
  '</svg>',
  '',
].join('\n');

const bytes = Buffer.byteLength(out, 'utf8');
if (bytes > MAX_BYTES) throw new Error(`sprite is ${bytes} bytes, over ${MAX_BYTES} limit; drop optional icons`);
writeFileSync(OUT, out, 'utf8');

mkdirSync(VENDOR, { recursive: true });
copyFileSync(join(LUCIDE, 'LICENSE'), join(VENDOR, 'LICENSE-lucide.txt'));
console.log(`wrote ${OUT}: ${entries.length} icons, ${bytes} bytes (limit ${MAX_BYTES})`);
